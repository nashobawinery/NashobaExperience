export function getZipCoordinates(zipCode: string): { lat: number; lng: number } | null {
  const normalized = zipCode.replace(/\D/g, '').padStart(5, '0').substring(0, 5);
  return zipCoordinates[normalized] || null;
}

export function calculateDistance(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const R = 3959;
  const dLat = toRad(lat2 - lat1);
  const dLng = toRad(lng2 - lng1);
  const a = 
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * 
    Math.sin(dLng / 2) * Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

function toRad(deg: number): number {
  return deg * (Math.PI / 180);
}

export function getDistanceFromZip(fromZip: string, toLat: number | null, toLng: number | null): number | null {
  if (toLat === null || toLng === null) return null;
  
  const fromCoords = getZipCoordinates(fromZip);
  if (!fromCoords) return null;
  
  return calculateDistance(fromCoords.lat, fromCoords.lng, Number(toLat), Number(toLng));
}
